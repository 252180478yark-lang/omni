def load_union(files):
    union = collections.defaultdict(list)
    seen = collections.defaultdict(set)
    for f in files:
        with open(f, encoding="utf-8-sig") as fh:
            r = csv.reader(fh)
            next(r)
            for row in r:
                if not row or not row[0].strip():
                    continue
                lt, val = row[0].strip(), row[1].strip()
                if val and val not in seen[lt]:
                    seen[lt].add(val)
                    union[lt].append(val)
    return union


def split_tree(values, sep):
    """把 '一级-二级' / '一级_二级' 平铺值拆成 {一级: [二级...]} 有序树。"""
    tree = collections.OrderedDict()
    for v in values:
        if sep in v:
            a, b = v.split(sep, 1)
            tree.setdefault(a, [])
            if b not in tree[a]:
                tree[a].append(b)
        else:
            tree.setdefault(v, [])
    return tree


